export function burnoutResult(score: number): {
  level: string
  tone: 'ok' | 'warn' | 'bad'
  advice: string
} {
  if (score <= 4) {
    return {
      level: '状态尚可',
      tone: 'ok',
      advice:
        '目前负担还在可承受范围。建议继续保留轮班和属于自己的时间，每月测一次看趋势，不要等撑不住才调整。',
    }
  }
  if (score <= 9) {
    return {
      level: '已出现照护疲劳信号',
      tone: 'warn',
      advice:
        '需要尽快做具体调整：把「可以放手」的事交出去、每周固定半天完全交班、保证连续 6 小时睡眠。如果两周内没有改善，建议向社区医生或心理咨询求助。',
    }
  }
  return {
    level: '明显耗竭，需要外部支持',
    tone: 'bad',
    advice:
      '这个分数说明你已经在透支。请尽快联系家人或社区安排替班，并向医生说明照护情况；长期耗竭会影响判断力，反而增加病人风险。照护者的状态也是治疗的一部分。',
  }
}

