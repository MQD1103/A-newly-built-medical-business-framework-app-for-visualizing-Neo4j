export function catGrade(score: number): { level: string; tip: string; tone: string } {
  if (score <= 9) {
    return {
      level: '轻微影响',
      tip: '症状控制较好，继续保持规律用药、运动与疫苗接种。',
      tone: 'ok',
    }
  }
  if (score <= 19) {
    return {
      level: '中等影响',
      tip: '建议复核吸入装置使用与用药方案，开始或加强肺康复训练。',
      tone: 'warn',
    }
  }
  if (score <= 29) {
    return {
      level: '严重影响',
      tip: '尽快复诊评估治疗方案，考虑肺康复、氧疗评估与营养支持。',
      tone: 'bad',
    }
  }
  return {
    level: '非常严重影响',
    tip: '属重度，需尽快就诊，评估氧疗/无创通气与综合照护方案。',
    tone: 'bad',
  }
}

