# 当前线上版本登记表：新增 / 修改协议文本时更新这里
AGREEMENTS: dict[str, Agreement] = {
    USER_AGREEMENT.agreement_type: USER_AGREEMENT,
    PRIVACY_POLICY.agreement_type: PRIVACY_POLICY,
}


def get_agreement(agreement_type: str) -> Agreement | None:
    return AGREEMENTS.get(agreement_type)


def current_version(agreement_type: str) -> str | None:
    agreement = AGREEMENTS.get(agreement_type)
    return agreement.version if agreement else None
